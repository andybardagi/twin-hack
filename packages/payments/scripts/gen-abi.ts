import { readFile, writeFile } from "node:fs/promises";

const artifactUrl = new URL(
  "../../../contracts/out/PaymentRouter.sol/PaymentRouter.json",
  import.meta.url,
);
const outputUrl = new URL("../src/abi.ts", import.meta.url);

const artifact: unknown = JSON.parse(await readFile(artifactUrl, "utf8"));
if (
  typeof artifact !== "object" ||
  artifact === null ||
  !("abi" in artifact) ||
  !Array.isArray(artifact.abi)
) {
  throw new Error(`No ABI in ${artifactUrl.pathname}; run \`forge build\` in contracts/ first`);
}

await writeFile(
  outputUrl,
  `// Generated by \`pnpm --filter @workspace/payments gen:abi\` from contracts/out. Do not edit.\nexport const paymentRouterAbi = ${JSON.stringify(artifact.abi)} as const;\n`,
);
